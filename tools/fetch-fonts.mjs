// Copies the app's one font, Nunito (latin subset, woff2, weights 600 to 900),
// from the @fontsource/nunito package into docs/fonts and writes
// docs/css/fonts.css. Run with: npm run fonts
// The app itself never loads fonts from the network at runtime.
import { readFile, writeFile, mkdir, readdir, rm, copyFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = path.join(root, 'node_modules', '@fontsource', 'nunito');
const fontDir = path.join(root, 'docs', 'fonts');
const cssFile = path.join(root, 'docs', 'css', 'fonts.css');
const WEIGHTS = [600, 700, 800, 900];
const RANGE = 'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD';

await mkdir(fontDir, { recursive: true });
for (const f of await readdir(fontDir)) if (f.endsWith('.woff2')) await rm(path.join(fontDir, f));
let css = '/* Generated by tools/fetch-fonts.mjs. Nunito is licensed under the SIL Open Font License (see fonts/OFL.txt). */\n';
for (const w of WEIGHTS) {
  const src = path.join(pkg, 'files', `nunito-latin-${w}-normal.woff2`);
  const hash = createHash('sha256').update(await readFile(src)).digest('hex').slice(0, 8);
  const name = `nunito-${w}-${hash}.woff2`;
  await copyFile(src, path.join(fontDir, name));
  css += `\n@font-face {\n  font-family: 'Nunito';\n  font-style: normal;\n  font-weight: ${w};\n  font-display: swap;\n  src: url('../fonts/${name}') format('woff2');\n  unicode-range: ${RANGE};\n}\n`;
}
await copyFile(path.join(pkg, 'LICENSE'), path.join(fontDir, 'OFL.txt'));
await writeFile(cssFile, css);
console.log(`Wrote ${WEIGHTS.length} Nunito weights and ${path.relative(root, cssFile)}`);
